#!/usr/bin/env python3
"""Create a deterministic Windows setup artifact for runner acceptance tests."""

from __future__ import annotations

import hashlib
import json
import os
import pathlib
import sys
from typing import Any


MARKER = "PACKAGING_PLATFORM_WINDOWS_SETUP_FIXTURE_V1"
SKIPPED_CONTEXT_FILES = {"context/build-info.json"}
SKIPPED_CONTEXT_PREFIXES = {"context/rendered/runner-cache-"}


def read_json(path: pathlib.Path) -> dict[str, Any]:
    if not path.exists():
        return {}
    return json.loads(path.read_text(encoding="utf-8"))


def sha256(path: pathlib.Path) -> str:
    digest = hashlib.sha256()
    with path.open("rb") as handle:
        for chunk in iter(lambda: handle.read(1024 * 1024), b""):
            digest.update(chunk)
    return digest.hexdigest()


def context_checksums(workspace: pathlib.Path) -> list[dict[str, str]]:
    context = workspace / "context"
    if not context.exists():
        raise RuntimeError(f"context directory does not exist: {context}")

    checksums: list[dict[str, str]] = []
    for path in sorted(item for item in context.rglob("*") if item.is_file()):
        relative = path.relative_to(workspace).as_posix()
        if relative in SKIPPED_CONTEXT_FILES:
            continue
        if any(relative.startswith(prefix) for prefix in SKIPPED_CONTEXT_PREFIXES):
            continue
        checksums.append({"path": relative, "sha256": sha256(path)})
    return checksums


def setup_metadata(workspace: pathlib.Path) -> dict[str, Any]:
    build_info = read_json(workspace / "context" / "build-info.json")
    build_lock = read_json(workspace / "context" / "build-lock.json")
    final_config = read_json(workspace / "context" / "final-config.json")
    components = read_json(workspace / "context" / "rendered" / "components.json")

    metadata = {
        "marker": MARKER,
        "buildId": build_info.get("buildId") or build_lock.get("buildId") or "",
        "productId": build_info.get("productId") or build_lock.get("productId") or "",
        "target": build_info.get("target") or build_lock.get("target") or "windows",
        "version": build_info.get("version") or build_lock.get("version") or "",
        "profile": build_info.get("profile") or build_lock.get("profile") or "",
        "customer": build_info.get("customer") or build_lock.get("customer") or "",
        "releaseChannel": build_info.get("releaseChannel") or build_lock.get("releaseChannel") or "",
        "componentCount": len(components) if isinstance(components, list) else 0,
        "installDir": final_config.get("installDir", ""),
        "contextChecksums": context_checksums(workspace),
    }
    metadata_bytes = json.dumps(metadata, sort_keys=True, separators=(",", ":")).encode("utf-8")
    metadata["payloadSha256"] = hashlib.sha256(metadata_bytes).hexdigest()
    return metadata


def write_setup(output: pathlib.Path, metadata: dict[str, Any]) -> None:
    payload = json.dumps(metadata, sort_keys=True, indent=2).encode("utf-8")
    header = b"MZ"
    dos_stub = (
        b"This program is a deterministic Vela Windows setup fixture.\r\n"
        b"It is generated by runner/fixtures/windows_setup_packager.py.\r\n"
    )
    body = b"\r\n".join(
        [
            header + dos_stub,
            MARKER.encode("ascii"),
            payload,
            hashlib.sha256(payload).hexdigest().encode("ascii"),
            b"",
        ]
    )
    output.parent.mkdir(parents=True, exist_ok=True)
    output.write_bytes(body)


def main() -> int:
    output_value = os.environ.get("OUTPUT", "")
    if not output_value:
        print("OUTPUT is required", file=sys.stderr)
        return 2

    workspace = pathlib.Path.cwd()
    output = pathlib.Path(output_value)
    metadata = setup_metadata(workspace)
    write_setup(output, metadata)
    print(f"created windows setup fixture: {output}")
    return 0


if __name__ == "__main__":
    try:
        sys.exit(main())
    except Exception as exc:
        print(str(exc), file=sys.stderr)
        sys.exit(1)
